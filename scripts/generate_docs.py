"""Generate the synthetic financial document corpus and the labelled doc-question set.

Produces ~200 documents under ``data/docs/`` (markdown, plus a share rendered as PDF) and
``data/eval/doc_questions.jsonl``. Every labelled question carries an *evidence span*: an
exact sentence fragment from the source document. ``scripts/eval.py`` resolves the span to
the chunk ids that contain it after ingestion, so labels survive chunker changes.

Questions are deliberately phrased differently from the evidence sentence (synonyms,
re-ordering) so pure keyword overlap is not enough – otherwise the eval would flatter BM25.

Fully deterministic (seeded), so the corpus can be regenerated byte-for-byte.
"""

