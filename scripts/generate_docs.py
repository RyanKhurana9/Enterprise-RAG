def build_faqs(rng: random.Random) -> list[Doc]:
    docs: list[Doc] = []
    for topic, items in FAQ_TOPICS:
        for region in FAQ_REGIONS:
            p = _params(rng) | {"region": region}
            p["amt"] = money(rng, 1_000, 250_000, 500)
            facts: list[Fact] = []
            parts = [
                f"# {topic} FAQ - {region}",
                f"Internal frequently asked questions for {region} employees. Last "
                f"updated {rng.choice(('March', 'June', 'September'))} 2025.",
            ]
            for q, a, eq in items:
                ans = a.format(**p)
                facts.append(Fact(ans, eq.format(**p)))
                parts.append(f"## {q}\n{ans}")
            for _ in range(2):
                parts.append(
                    "## "
                    + rng.choice(
                        (
                            "Who do I contact with further questions?",
                            "Where can I find the full policy?",
                            "Does this apply to contractors?",
                        )
                    )
                    + "\n"
                    + rng.choice(
                        (
                            "Contact the regional HR Service Centre through the employee portal.",
                            "The full policy is published on the intranet policy library.",
                            "Contractors should refer to the terms of their agency agreement.",
                        )
                    )
                )
            docs.append(
                Doc(
                    doc_id=slug(f"faq {topic} {region}"),
                    title=f"{topic} FAQ ({region})",
                    doc_type="faq",
                    body="\n\n".join(parts) + "\n",
                    facts=facts,
                )
            )
    return docs


# ------------------------------------------------------------------------------ output ---
def write_pdf(path: Path, text: str) -> None:
    from fpdf import FPDF

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    for line in text.splitlines():
        if line.startswith("#"):
            pdf.set_font("Helvetica", "B", 13 if line.startswith("# ") else 11)
            line = line.lstrip("# ")
        else:
            pdf.set_font("Helvetica", size=10)
        pdf.multi_cell(0, 5, line.encode("latin-1", "replace").decode("latin-1"))
        pdf.ln(1)
    pdf.output(str(path))


def main() -> None:
    rng = random.Random(SEED)
    fake = Faker()
    Faker.seed(SEED)

    docs = build_policies(rng) + build_10ks(rng, fake, 106) + build_faqs(rng)
    # ~10% of the corpus is rendered as PDF to exercise the PdfLoader path.
    for d in rng.sample(docs, 20):
        d.fmt = "pdf"

    if DOCS_DIR.exists():
        shutil.rmtree(DOCS_DIR)
    for sub in ("policies", "10k", "faq"):
        (DOCS_DIR / sub).mkdir(parents=True, exist_ok=True)
    sub_for = {"policy": "policies", "10k": "10k", "faq": "faq"}
    for d in docs:
        target = DOCS_DIR / sub_for[d.doc_type] / f"{d.doc_id}.{d.fmt}"
        if d.fmt == "pdf":
            write_pdf(target, d.body)
        else:
            target.write_text(d.body)

    # 50 labelled questions, stratified: 22 policy, 16 10-K, 12 FAQ.
    by_type: dict[str, list[tuple[Doc, Fact]]] = {"policy": [], "10k": [], "faq": []}
    for d in docs:
        for f in d.facts:
            by_type[d.doc_type].append((d, f))
    picked = (
        rng.sample(by_type["policy"], 22)
        + rng.sample(by_type["10k"], 16)
        + rng.sample(by_type["faq"], 12)
    )
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    with (EVAL_DIR / "doc_questions.jsonl").open("w") as fh:
        for i, (d, f) in enumerate(picked, 1):
            # Evidence span: the sentence minus its final period. PDF extraction may re-wrap
            # lines, so eval matching normalises whitespace.
            fh.write(
                json.dumps(
                    {
                        "id": f"D{i:02d}",
                        "question": f.question,
                        "doc_id": d.doc_id,
                        "evidence": f.sentence.rstrip("."),
                        "route": "docs",
                    }
                )
                + "\n"
            )
    n_pdf = sum(d.fmt == "pdf" for d in docs)
    print(f"wrote {len(docs)} docs ({n_pdf} pdf) and {len(picked)} labelled questions")


if __name__ == "__main__":
    main()
