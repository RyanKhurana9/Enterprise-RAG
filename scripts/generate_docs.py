def _params(rng: random.Random) -> dict[str, str]:
    return {
        "n": str(rng.randint(2, 9)),
        "m": str(rng.choice((10, 15, 20, 30, 45, 60, 90))),
        "amt": money(rng, 5_000, 2_000_000, 5_000),
        "role": rng.choice(ROLES),
        "days": str(rng.choice((5, 7, 10, 14, 21, 30, 45, 60, 90))),
        "pct": str(rng.choice((10, 15, 20, 25, 50, 75, 105, 110, 120))),
        "hrs": str(rng.choice((4, 5, 6, 7, 8, 24, 48))),
        "yrs": str(rng.choice((5, 6, 7, 10))),
    }


def build_policies(rng: random.Random) -> list[Doc]:
    docs: list[Doc] = []
    for title, rules in POLICY_TOPICS:
        for div in DIVISIONS:
            p = _params(rng) | {"div": div}
            facts = [Fact(s.format(**p), q.format(**p)) for s, q in rules]
            version = f"{rng.randint(1, 6)}.{rng.randint(0, 9)}"
            effective = f"{rng.choice(('January', 'April', 'July', 'October'))} 1, 2025"
            parts = [
                f"# {div} {title}",
                f"Version {version}. Effective {effective}. Policy owner: "
                f"{rng.choice(ROLES)[4:].title()}.",
            ]
            for section in ("Purpose", "Scope", "Definitions"):
                parts.append(f"## {section}")
                k = min(len(GENERIC_POLICY_SECTIONS[section]), 3)
                parts.append(" ".join(rng.sample(GENERIC_POLICY_SECTIONS[section], k)))
            parts.append("## Policy Requirements")
            for i, f in enumerate(facts, 1):
                parts.append(
                    f"{i}. {f.sentence} "
                    + rng.choice(
                        (
                            "Evidence of compliance must be retained for audit.",
                            "Controls are tested quarterly by the first line of defence.",
                            "Deviations are logged and escalated to the policy owner.",
                            "This requirement is monitored through automated surveillance.",
                        )
                    )
                )
            for section in (
                "Roles and Responsibilities",
                "Monitoring and Reporting",
                "Exceptions",
                "Breaches",
                "Review",
            ):
                parts.append(f"## {section}")
                parts.append(" ".join(rng.sample(GENERIC_POLICY_SECTIONS[section], 2)))
            docs.append(
                Doc(
                    doc_id=slug(f"policy {div} {title}"),
                    title=f"{div} {title}",
                    doc_type="policy",
                    body="\n\n".join(parts) + "\n",
                    facts=facts,
                )
            )
    return docs


