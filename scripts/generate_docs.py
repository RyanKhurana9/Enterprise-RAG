@dataclass
class Fact:
    sentence: str  # appears verbatim in the doc -> evidence span
    question: str  # paraphrased question


@dataclass
class Doc:
    doc_id: str
    title: str
    doc_type: str
    body: str
    facts: list[Fact] = field(default_factory=list)
    fmt: str = "md"


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def money(rng: random.Random, lo: int, hi: int, step: int = 1000) -> str:
    return f"{rng.randrange(lo, hi, step):,}"


